import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)))
mkdirSync(join(rootDir, 'dist'), { recursive: true })

const [serverBuild, clientBuild] = await Promise.all([
  build({
    entryPoints: [join(rootDir, 'src/server/index.mjs')],
    outfile: join(rootDir, 'dist/server.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    external: ['node:*'],
    minify: false,
    sourcemap: false,
    metafile: true,
    banner: {
      js: [
        '/* Ekko ToDo server bundle (self-contained Node ESM; external: node:*) */',
        'import { createRequire as __ekkoCreateRequire } from "node:module";',
        'const require = __ekkoCreateRequire(import.meta.url);',
      ].join('\n'),
    },
  }),
  build({
    entryPoints: [join(rootDir, 'src/client/index.jsx')],
    outfile: join(rootDir, 'dist/client.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2022'],
    jsx: 'automatic',
    minify: true,
    sourcemap: false,
    metafile: true,
    define: {
      'process.env.NODE_ENV': '"production"',
    },
    loader: {
      '.css': 'text',
    },
    banner: {
      js: '/* Ekko ToDo client bundle (self-contained Browser ESM; React + Radix UI + Phosphor Icons) */',
    },
  }),
])

// Which packages actually end up inside the shipped bundles. The client bundle is minified, so its module
// paths are not readable afterwards; the metafiles are the only record. THIRD-PARTY-NOTICES.md is generated
// from this file, and tests/third-party-notices.test.mjs fails when it drifts from `dist/server.mjs`.
const packages = new Set()
for (const result of [serverBuild, clientBuild]) {
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//)
    if (match) packages.add(match[1])
  }
}
writeFileSync(
  join(rootDir, 'dist/bundled-packages.json'),
  `${JSON.stringify({ note: 'Generated by scripts/build.mjs from the esbuild metafiles. Do not edit.', packages: [...packages].sort() }, null, 2)}\n`,
)

// esbuild labels each compiled module with the path it was read from. Resolved through a symlinked or nested
// node_modules that label is a chain of `../`, which bakes the build machine's directory layout into the
// shipped file: the same source then produces different bytes in different checkouts, and the maintainer's
// directory names become readable by anyone who installs the plugin. These labels are comments and CommonJS
// wrapper keys, never lookups, so flattening them to `node_modules/…` changes no behaviour and makes the
// committed bundle reproducible.
const DEP_PATH_LABEL = /(?:\.\.\/)+[^"'\s()]*?node_modules\//g
for (const file of ['dist/server.mjs', 'dist/client.mjs']) {
  const path = join(rootDir, file)
  const before = readFileSync(path, 'utf8')
  const after = before.replace(DEP_PATH_LABEL, 'node_modules/')
  if (after !== before) writeFileSync(path, after)
}

console.log('Built dist/server.mjs and dist/client.mjs successfully.')
