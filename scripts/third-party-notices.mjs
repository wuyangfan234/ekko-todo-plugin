#!/usr/bin/env node
// Builds THIRD-PARTY-NOTICES.md from what the shipped bundles actually contain.
//
// The two dist/ files are self-contained: every runtime dependency is compiled in, so distributing them is
// redistributing those packages. The package list comes from `dist/bundled-packages.json`, which
// scripts/build.mjs derives from the esbuild metafiles — package.json cannot say which dependencies reached a
// bundle, and the minified client bundle no longer shows its module paths.
//
//   node scripts/third-party-notices.mjs --write   regenerate the file
//   node scripts/third-party-notices.mjs --check   exit 1 when the file and the bundles disagree
//
// `--check` is also what the test suite calls, so a release that adds or drops a bundled package without
// touching the notices file fails the gate instead of shipping an incomplete notice.

import { existsSync, readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const NOTICE_FILE = 'THIRD-PARTY-NOTICES.md'
export const MANIFEST_FILE = 'dist/bundled-packages.json'
const LICENSE_FILE = /^(?:licen[cs]e|copying|copyright)(?:[.-].*)?$/i

/** The packages the build recorded as bundled, in the order the manifest lists them. */
export function bundledPackages(rootDir = PKG_ROOT) {
  const manifest = JSON.parse(readFileSync(join(rootDir, MANIFEST_FILE), 'utf8'))
  return [...new Set(manifest.packages || [])].sort()
}

/** Package names still readable in a bundle's module-path comments (the unminified server bundle only). */
export function packagesInBundleComments(rootDir = PKG_ROOT) {
  const text = readFileSync(join(rootDir, 'dist/server.mjs'), 'utf8')
  const names = new Set()
  for (const match of text.matchAll(/node_modules\/((?:@[^/\s"']+\/)?[^/\s"']+)\//g)) names.add(match[1])
  return [...names].sort()
}

/** The licence a package ships: its declared id, and the text of the licence file it carries. */
export function readLicence(rootDir, pkgName) {
  const dir = join(rootDir, 'node_modules', pkgName)
  const metaPath = join(dir, 'package.json')
  if (!existsSync(metaPath)) return null
  const meta = JSON.parse(readFileSync(metaPath, 'utf8'))
  const declared = typeof meta.license === 'string'
    ? meta.license
    : (meta.license?.type || (Array.isArray(meta.licenses) ? meta.licenses.map(l => l?.type).filter(Boolean).join(' OR ') : ''))
  const files = existsSync(dir) ? readdirSync(dir).filter(f => LICENSE_FILE.test(f)) : []
  // Longest match wins: a package can ship both `LICENSE` and `LICENSE-MIT`; the fuller text is the useful one.
  const texts = []
  for (const file of files.sort((a, b) => a.length - b.length || a.localeCompare(b))) {
    const body = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim()
    if (body && !texts.includes(body)) texts.push(body)
  }
  return {
    name: pkgName,
    version: String(meta.version || ''),
    license: declared || 'UNKNOWN',
    repository: typeof meta.repository === 'string' ? meta.repository : (meta.repository?.url || ''),
    texts,
  }
}

export function renderNotices(entries) {
  const lines = [
    '# Third-Party Notices',
    '',
    'Both `dist/server.mjs` and `dist/client.mjs` are self-contained bundles: the packages below are compiled',
    'into them, so every copy of this plugin redistributes those packages. Their licences follow.',
    '',
    'This file is generated by `node scripts/third-party-notices.mjs --write` from the bundled modules and the',
    'licence files inside `node_modules`. `npm test` fails when it no longer matches the bundles.',
    '',
    `Bundled packages: **${entries.length}**.`,
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
  ]
  for (const e of entries) lines.push(`| \`${e.name}\` | ${e.version || '—'} | ${e.license} |`)
  lines.push('', '---', '', '## Licence texts', '')
  for (const e of entries) {
    lines.push(`### ${e.name}${e.version ? `@${e.version}` : ''}`, '')
    lines.push(`Declared licence: \`${e.license}\`${e.repository ? ` · ${e.repository}` : ''}`, '')
    if (!e.texts.length) {
      lines.push('_This package ships no licence file. Its declared licence above applies._', '')
      continue
    }
    for (const text of e.texts) {
      lines.push('```', text, '```', '')
    }
  }
  return `${lines.join('\n').trimEnd()}\n`
}

/** The notices file the current bundles require. */
export function expectedNotices(rootDir = PKG_ROOT) {
  const entries = []
  for (const name of bundledPackages(rootDir)) {
    const licence = readLicence(rootDir, name)
    if (licence) entries.push(licence)
  }
  return { entries, content: renderNotices(entries) }
}

/** Package names the current notices file claims, for a two-way comparison in the gate. */
export function declaredPackages(content) {
  return [...content.matchAll(/^\| `([^`]+)` \|/gm)].map(m => m[1]).sort()
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const mode = process.argv[2]
  const { entries, content } = expectedNotices()
  if (mode === '--write') {
    writeFileSync(join(PKG_ROOT, NOTICE_FILE), content)
    console.log(`Wrote ${NOTICE_FILE}: ${entries.length} packages`)
  } else if (mode === '--check') {
    const current = existsSync(join(PKG_ROOT, NOTICE_FILE)) ? readFileSync(join(PKG_ROOT, NOTICE_FILE), 'utf8') : ''
    const declared = declaredPackages(current)
    const actual = entries.map(e => e.name).sort()
    const missing = actual.filter(n => !declared.includes(n))
    const extra = declared.filter(n => !actual.includes(n))
    if (missing.length || extra.length) {
      console.error(`missing: ${missing.join(', ') || 'none'}`)
      console.error(`extra: ${extra.join(', ') || 'none'}`)
      process.exitCode = 1
    } else if (current !== content) {
      console.error(`${NOTICE_FILE} is out of date; run node scripts/third-party-notices.mjs --write`)
      process.exitCode = 1
    } else {
      console.log(`${NOTICE_FILE} matches the ${actual.length} bundled packages`)
    }
  } else {
    console.error('usage: node scripts/third-party-notices.mjs --write|--check')
    process.exitCode = 2
  }
}
